#!/usr/bin/env python3
"""Regenerate test/vectors.ml from the mldsa-native example test vectors.
Usage: gen_vectors.py <path-to-mldsa-native>/examples/monolithic_build_multilevel/expected_test_vectors_multilevel.h > vectors.ml
"""
import re, sys
src = open(sys.argv[1]).read()
msg = re.search(r'#define TEST_VECTOR_MSG \\\n\s*"([^"]*)"', src).group(1)
ctx = re.search(r'#define TEST_VECTOR_CTX "([^"]*)"', src).group(1)
print('(* Known-answer vectors, extracted from mldsa-native\n   examples/monolithic_build_multilevel/expected_test_vectors_multilevel.h\n   (see ../VENDORED for the upstream commit). Generated by test/gen_vectors.py;\n   do not edit by hand. *)\n')
print(f'let msg = "{msg}"\nlet ctx = "{ctx}"')
for m in re.finditer(r'static const uint8_t (\w+)\[(\d+)\] = \{([^}]*)\};', src, re.S):
    name, n, body = m.groups(); n = int(n)
    vals = [int(x, 0) for x in re.findall(r'0x[0-9a-fA-F]+|\b\d+\b', body)]
    if len(vals) == 1 and vals[0] == 0 and n > 1: vals = [0] * n
    assert len(vals) == n, (name, len(vals), n)
    hx = ''.join('%02x' % v for v in vals)
    print(f'let {name} = String.concat "" [')
    for i in range(0, len(hx), 64): print('  "%s";' % hx[i:i+64])
    print(']')
